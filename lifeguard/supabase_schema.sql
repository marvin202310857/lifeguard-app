-- LifeGuard PostgreSQL schema for Supabase.
-- Review before running. The migration script creates these objects automatically.
CREATE TABLE admin_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL,
    username TEXT,
    message TEXT NOT NULL,
    ip_address TEXT,
    created_at TEXT NOT NULL,
    acknowledged INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cam_id TEXT NOT NULL,
    track_id BIGINT,
    event TEXT NOT NULL,
    alert_level TEXT DEFAULT 'WARNING',
    elapsed_sec BIGINT DEFAULT 0,
    started_at TEXT,
    created_at TEXT NOT NULL,
    resolved_at TEXT,
    status TEXT NOT NULL DEFAULT 'ACTIVE',
    snapshot BYTEA,
    video BYTEA,
    video_mime TEXT,
    video_state TEXT NOT NULL DEFAULT 'RECORDING',
    snapshot_path TEXT,
    video_path TEXT,
    client_ref TEXT
);

CREATE TABLE login_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT,
    event TEXT NOT NULL,
    success INTEGER NOT NULL DEFAULT 0,
    ip_address TEXT,
    user_agent TEXT,
    detail TEXT,
    created_at TEXT NOT NULL
);

CREATE TABLE login_throttle (
    username TEXT PRIMARY KEY,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until DOUBLE PRECISION NOT NULL DEFAULT 0,
    last_attempt DOUBLE PRECISION NOT NULL DEFAULT 0
);

CREATE TABLE occupancy_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id TEXT NOT NULL,
    people_in_pool INTEGER NOT NULL DEFAULT 0,
    people_poolside INTEGER NOT NULL DEFAULT 0,
    submerged_count INTEGER NOT NULL DEFAULT 0,
    timestamp TEXT NOT NULL
);

CREATE TABLE system_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE uplink_map (
    local_id BIGINT PRIMARY KEY,
    cloud_id BIGINT NOT NULL
);

CREATE TABLE uplink_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL,
    incident_id BIGINT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL
);

CREATE TABLE users (
    id TEXT PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT,
    role TEXT NOT NULL DEFAULT 'User',
    approved INTEGER NOT NULL DEFAULT 0,
    created_at TEXT
);

CREATE INDEX idx_incidents_created ON incidents (created_at);
CREATE UNIQUE INDEX idx_incidents_ref ON incidents (client_ref) WHERE client_ref IS NOT NULL;
CREATE INDEX idx_occupancy_timestamp ON occupancy_logs (timestamp);
-- SQLite used COLLATE NOCASE for these username fields. PostgreSQL uses explicit
-- lower-case unique indexes to preserve case-insensitive uniqueness for usernames.
CREATE UNIQUE INDEX uq_users_username_lower ON users (LOWER(username));
CREATE UNIQUE INDEX uq_login_throttle_username_lower ON login_throttle (LOWER(username));
