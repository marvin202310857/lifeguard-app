"""
One-time LifeGuard SQLite -> PostgreSQL migration helper.

Run locally from the project root after setting DATABASE_URL in your
PowerShell session. It reads lifeguard-backup.db by default and refuses to
run if the target PostgreSQL database already contains user tables.

This migrates table columns and rows (including BLOB media) dynamically.
It does NOT convert the application db.py to PostgreSQL; that is a separate
step and must be completed before the live app can use PostgreSQL.
"""
from __future__ import annotations

import os
import sqlite3
import sys
from pathlib import Path

import psycopg
from psycopg import sql

ROOT = Path(__file__).resolve().parent
SOURCE_DB = Path(os.environ.get("LIFEGUARD_MIGRATION_SOURCE", ROOT / "lifeguard-backup.db"))
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()

SKIP_TABLES = {"sqlite_sequence", "sqlite_stat1", "sqlite_stat4"}


def quote_table(name: str):
    return sql.Identifier(name)


def pg_type(sqlite_type: str, is_auto_id: bool = False) -> str:
    if is_auto_id:
        return "BIGINT GENERATED BY DEFAULT AS IDENTITY"
    t = (sqlite_type or "").upper()
    if "INT" in t:
        return "BIGINT"
    if any(x in t for x in ("BLOB", "BINARY")) or not t:
        return "BYTEA" if "BLOB" in t or "BINARY" in t else "TEXT"
    if any(x in t for x in ("REAL", "FLOA", "DOUB")):
        return "DOUBLE PRECISION"
    if any(x in t for x in ("NUMERIC", "DECIMAL")):
        return "NUMERIC"
    if "BOOL" in t:
        return "BOOLEAN"
    return "TEXT"


def get_tables(src: sqlite3.Connection):
    rows = src.execute(
        "SELECT name FROM sqlite_master WHERE type='table' ORDER BY name"
    ).fetchall()
    return [r[0] for r in rows if r[0] not in SKIP_TABLES and not r[0].startswith("sqlite_")]


def column_definitions(src: sqlite3.Connection, table: str):
    info = src.execute(f"PRAGMA table_info({quote_sqlite_name(table)})").fetchall()
    if not info:
        raise RuntimeError(f"Could not inspect SQLite table {table!r}")
    # PRAGMA columns: cid, name, type, notnull, default, pk
    pk_cols = [row[1] for row in sorted(info, key=lambda x: x[5]) if row[5]]
    definitions = []
    for row in info:
        _, name, decl_type, not_null, default_value, pk_order = row
        auto_id = bool(pk_order and len(pk_cols) == 1 and "INT" in (decl_type or "").upper())
        dtype = pg_type(decl_type, is_auto_id=auto_id)
        pieces = [sql.Identifier(name), sql.SQL(dtype)]
        if not_null and not pk_order:
            pieces.append(sql.SQL("NOT NULL"))
        if pk_order and not auto_id:
            # Single/composite non-integer primary keys are added below.
            pass
        definitions.append(sql.SQL(" ").join(pieces))
    if pk_cols and not any(
        row[5] and len(pk_cols) == 1 and "INT" in (row[2] or "").upper()
        for row in info
    ):
        definitions.append(
            sql.SQL("PRIMARY KEY ({})").format(
                sql.SQL(", ").join(sql.Identifier(c) for c in pk_cols)
            )
        )
    return info, definitions


def quote_sqlite_name(name: str) -> str:
    # SQLite identifier quoting for PRAGMA statements.
    return '"' + name.replace('"', '""') + '"'


def ensure_target_empty(pg):
    with pg.cursor() as cur:
        cur.execute("""
            SELECT tablename
            FROM pg_catalog.pg_tables
            WHERE schemaname = 'public'
              AND tablename NOT LIKE 'pg_%'
              AND tablename NOT LIKE 'sql_%'
            ORDER BY tablename
        """)
        existing = [r[0] for r in cur.fetchall()]
    if existing:
        raise RuntimeError(
            "Target database is not empty; refusing to risk overwriting it. "
            f"Existing public tables: {', '.join(existing)}"
        )


def create_table(pg, src, table: str):
    info, definitions = column_definitions(src, table)
    stmt = sql.SQL("CREATE TABLE {} ({})").format(
        quote_table(table), sql.SQL(", ").join(definitions)
    )
    with pg.cursor() as cur:
        cur.execute(stmt)
    return info


def copy_table(pg, src, table: str, info):
    names = [row[1] for row in info]
    col_sql = sql.SQL(", ").join(sql.Identifier(n) for n in names)
    placeholders = sql.SQL(", ").join(sql.Placeholder() for _ in names)
    insert_stmt = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
        quote_table(table), col_sql, placeholders
    )
    source_cols = ", ".join(quote_sqlite_name(n) for n in names)
    rows = src.execute(f"SELECT {source_cols} FROM {quote_sqlite_name(table)}").fetchall()
    with pg.cursor() as cur:
        for row in rows:
            cur.execute(insert_stmt, row)
    return len(rows)


def reset_identity_sequences(pg, tables):
    # Set identity sequences to the maximum imported value so future inserts
    # don't collide with migrated IDs.
    with pg.cursor() as cur:
        for table, info in tables.items():
            for row in info:
                _, column, declared_type, _, _, pk_order = row
                is_auto_id = bool(
                    pk_order and "INT" in (declared_type or "").upper()
                    and sum(1 for r in info if r[5]) == 1
                )
                if not is_auto_id:
                    continue
                cur.execute(
                    sql.SQL("SELECT MAX({}) FROM {}").format(
                        sql.Identifier(column), sql.Identifier(table)
                    )
                )
                max_id = cur.fetchone()[0]
                if max_id is not None:
                    cur.execute(
                        "SELECT setval(pg_get_serial_sequence(%s, %s), %s, true)",
                        (f"public.{table}", column, max_id),
                    )


def main():
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is not set. Set it in this PowerShell session; "
            "do not put the connection string in this script."
        )
    if not SOURCE_DB.is_file():
        raise FileNotFoundError(
            f"Backup database not found: {SOURCE_DB}\n"
            "Place lifeguard-backup.db beside this script or set "
            "LIFEGUARD_MIGRATION_SOURCE to its full path."
        )

    with sqlite3.connect(f"file:{SOURCE_DB.as_posix()}?mode=ro", uri=True) as src:
        integrity = src.execute("PRAGMA integrity_check").fetchone()[0]
        if integrity != "ok":
            raise RuntimeError(f"SQLite backup integrity check failed: {integrity}")
        tables = get_tables(src)
        if not tables:
            raise RuntimeError("No SQLite user tables found in the backup.")

        with psycopg.connect(DATABASE_URL, autocommit=False) as pg:
            ensure_target_empty(pg)
            migrated = {}
            counts = {}
            try:
                for table in tables:
                    info = create_table(pg, src, table)
                    migrated[table] = info
                    counts[table] = copy_table(pg, src, table, info)
                reset_identity_sequences(pg, migrated)
                pg.commit()
            except Exception:
                pg.rollback()
                raise

    print(f"Migration completed from: {SOURCE_DB}")
    print("Imported record counts:")
    for table in tables:
        print(f"  {table}: {counts[table]}")
    print(f"TOTAL: {sum(counts.values())}")
    print("\nImportant: this script copies schema columns and rows, including BLOBs.")
    print("It does not migrate SQLite indexes/triggers or make app/db.py PostgreSQL-compatible.")
    print("Do not switch the live app until those are addressed and counts are verified.")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print(f"MIGRATION STOPPED: {exc}", file=sys.stderr)
        sys.exit(1)
